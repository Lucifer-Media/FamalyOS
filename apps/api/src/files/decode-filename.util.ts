/**
 * Express/Multer по умолчанию декодирует заголовок filename из multipart-запроса
 * как latin1 (ISO-8859-1), даже если браузер реально отправил его в UTF-8 —
 * отсюда кракозябры вида "Ð Ð¾ÑÑÐ¸Ð¹ÑÐºÐ°Ñ..." для файлов с русскими именами.
 * Это известное, задокументированное поведение busboy/multer, а не баг
 * конкретного файла. Исправление — перекодировать байты обратно в UTF-8.
 */
export function decodeOriginalFilename(name: string): string {
  try {
    const fixed = Buffer.from(name, 'latin1').toString('utf8');
    // Простая эвристика: если результат содержит символ замены (некорректная
    // UTF-8 последовательность), исходное имя, скорее всего, и так было
    // валидным UTF-8 (например, чисто латинское имя) — не портим его.
    return fixed.includes('\uFFFD') ? name : fixed;
  } catch {
    return name;
  }
}
